import { DatabaseSync } from 'node:sqlite';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildArtifact } from '../src/artifact.mjs';
import { isoNow, jsonString, sha256, uid } from '../src/utils.mjs';

export function planRegeneration(db, ids = null) {
  const rows = db.prepare(`SELECT c.*,a.manifest_json previous_manifest,a.checksum previous_checksum
    FROM contents c LEFT JOIN content_artifacts a ON a.content_id=c.id AND a.version=c.current_version
    WHERE c.content_type='game' AND c.current_version>0 ORDER BY c.id`).all();
  if (ids && ids.some(id => !rows.some(row => row.id === id))) throw new Error('Requested content ID is missing, not a game, or has no version.');
  return rows.filter(row => !ids || ids.includes(row.id)).map(content => {
    const previous = JSON.parse(content.previous_manifest || '{}');
    const maxVersion = db.prepare(`SELECT MAX(version) version FROM (SELECT version FROM content_versions WHERE content_id=? UNION ALL SELECT version FROM content_artifacts WHERE content_id=?)`).get(content.id, content.id).version || content.current_version;
    const artifact = buildArtifact({ content, payload: JSON.parse(content.payload_json), version: maxVersion + 1 });
    const blocked = content.campaign_id || content.contract_version ? 'campaign_bound_content_requires_campaign_workflow' : !artifact.validation.passed ? 'artifact_validation_failed' : null;
    return { id: content.id, title: content.title, status: content.status, fromVersion: content.current_version, toVersion: maxVersion + 1,
      previousRuntime: previous.runtime || 'artifact-v1', runtime: artifact.manifest.runtime, gameKey: artifact.manifest.gameKey,
      mechanic: artifact.manifest.mechanic, blocked, alreadyCurrent: previous.runtimeVersion === '3.2.0' && previous.gameplayAssetPack === 'casual-v1',
      payloadChecksum: sha256(content.payload_json), previousArtifactChecksum: content.previous_checksum,
    };
  });
}

export function applyRegeneration(db, plan) {
  if (!Array.isArray(plan) || !plan.length) throw new Error('Explicit non-empty content plan required.');
  if (plan.some(item => item.blocked)) throw new Error('The plan contains blocked content.');
  db.exec('BEGIN IMMEDIATE');
  try {
    const applied = [];
    for (const item of plan) {
      const content = db.prepare('SELECT * FROM contents WHERE id=?').get(item.id);
      if (!content || content.content_type !== 'game' || content.current_version !== item.fromVersion || sha256(content.payload_json) !== item.payloadChecksum) throw new Error(`Content changed since plan: ${item.id}`);
      if (content.campaign_id || content.contract_version) throw new Error(`Campaign-bound content cannot be regenerated by this local tool: ${item.id}`);
      if (db.prepare('SELECT id FROM content_artifacts WHERE content_id=? AND version=?').get(item.id, item.toVersion)
        || db.prepare('SELECT id FROM content_versions WHERE content_id=? AND version=?').get(item.id, item.toVersion)) throw new Error(`Version already exists: ${item.id} v${item.toVersion}`);
      const now = isoNow();
      const artifact = buildArtifact({ content, payload: JSON.parse(content.payload_json), version: item.toVersion });
      if (!artifact.validation.passed) throw new Error(`Artifact validation failed: ${item.id}`);
      const checksum = sha256(artifact.html);
      Object.assign(artifact.manifest, { checksum, campaignId: null, contractVersion: null,
        regeneration: { fromVersion: item.fromVersion, previousChecksum: item.previousArtifactChecksum, tool: 'regenerate-game-artifacts-v3', generatedAt: now, scope: 'LOCAL_DEMO' } });
      db.prepare(`INSERT INTO content_versions (id,content_id,version,title,payload_json,created_by,campaign_id,contract_version,created_at) VALUES (?,?,?,?,?,?,NULL,NULL,?)`)
        .run(uid('ver'), content.id, item.toVersion, content.title, content.payload_json, content.owner_user_id, now);
      db.prepare(`INSERT INTO content_artifacts (id,content_id,version,artifact_type,status,html_text,manifest_json,validation_json,checksum,campaign_id,contract_version,created_at) VALUES (?,?,?,'game','ready',?,?,?,?,NULL,NULL,?)`)
        .run(uid('artifact'), content.id, item.toVersion, artifact.html, jsonString(artifact.manifest), jsonString(artifact.validation), checksum, now);
      db.prepare('UPDATE contents SET current_version=?,updated_at=? WHERE id=?').run(item.toVersion, now, content.id);
      applied.push({ ...item, checksum });
    }
    db.exec('COMMIT'); return applied;
  } catch (error) { db.exec('ROLLBACK'); throw error; }
}

function main() {
  const args = process.argv.slice(2); const apply = args.includes('--apply'); const dryRun = args.includes('--dry-run');
  const value = name => { const index = args.indexOf(name); return index < 0 ? null : args[index + 1]; };
  if (apply && dryRun) throw new Error('Choose --dry-run or --apply.');
  const ids = value('--ids')?.split(',').filter(Boolean) || null;
  if (apply && !ids?.length) throw new Error('--apply requires --ids with the exact comma-separated IDs from the dry run.');
  const allowed = new Set(['--apply', '--dry-run', '--ids', '--db']);
  for (let i = 0; i < args.length; i++) { if (!allowed.has(args[i])) throw new Error(`Unknown argument: ${args[i]}`); if (['--ids','--db'].includes(args[i])) i++; }
  const file = path.resolve(value('--db') || fileURLToPath(new URL('../data/airvana.db', import.meta.url)));
  const db = new DatabaseSync(file, { readOnly: !apply });
  try {
    const plan = planRegeneration(db, ids);
    const result = apply ? applyRegeneration(db, plan) : plan;
    console.log(JSON.stringify({ mode: apply ? 'applied' : 'dry-run', scope: 'LOCAL_DEMO', database: file, count: result.length,
      native: result.filter(row => row.mechanic === 'native').length, decisions: result.filter(row => row.mechanic === 'decision').length,
      memory: result.filter(row => row.mechanic === 'memory').length, blocked: result.filter(row => row.blocked).length,
      previousVersionsPreserved: true, contentPayloadsPreserved: true, productionPublished: false, games: result }, null, 2));
  } finally { db.close(); }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
